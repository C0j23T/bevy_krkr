"""Regenerate host TJS exports from Kirikiroid2's generated legacy stub table."""
from pathlib import Path
import re
import zlib

root = Path(__file__).resolve().parents[2]
source = (root / 'Kirikiroid2/src/core/base/win32/FuncStubs.cpp').read_text()
compressed = source.split('static tjs_uint8 compressed_functable[] = {', 1)[1].split('};', 1)[0]
names = zlib.decompress(bytes(int(x, 0) for x in re.findall(r'0x[0-9a-fA-F]+|\d+', compressed))).split(b'\0')
ids = re.findall(r'TVP_Stub_([0-9a-f]+)', source.split('static void *func_ptrs[]', 1)[1].split('};', 1)[0]) if 'static void *func_ptrs[]' in source else []
if not ids:
    start = source.index('func_ptrs')
    ids = re.findall(r'TVP_Stub_([0-9a-f]+)', source[start:source.index('void TVPExportFunctions', start)])
lookup = dict(zip(ids, (n.decode() for n in names)))
prefix = source[:source.index('#include "StorageIntf.h"')].replace('__stdcall', 'TJS_INTF_METHOD')
wrappers = re.findall(r'static [^\n]+ TVP_Stub_([0-9a-f]+)\(', prefix)
result = '// Generated by tools/external-plugins/generate_tjs_exports.py.\n' + prefix
result += '\nvoid TVPBevyExportTJSFunctions() {\n'
for key in wrappers:
    name = lookup[key].replace('\\', '\\\\').replace('"', '\\"')
    result += f'    TVPAddExportFunction("{name}", reinterpret_cast<void *>(TVP_Stub_{key}));\n'
result += '}\n'
(root / 'Kirikiroid2/src/core/environ/bevy/ExternalTJSExports.cpp').write_text(result)
